from pydantic import BaseModel, Field
from typing import List, Optional, Any

# analytics schema

class KPISummary(BaseModel):
    """"Overall business metrics for the dashboard KPI"""

    total_revenue: float = Field(..., description="Total completed revenue")
    total_orders: int = Field(..., description="Total number of orders")
    total_customers: int = Field(..., description="Total number of customers")
    average_order_value: float = Field(..., description="Average order value")

class MonthlyRevenue(BaseModel):
    """Revenue data for a single month"""
    month: str = Field(..., description="Month in YYYY-MM format")
    revenue: float = Field(..., description="Revenue for the month")

class TopProductItems(BaseModel):
    """Product performance data"""

    product_id: int
    name: str = Field(..., description="Name of the product")
    category: str = Field(..., description="Category of the product")
    revenue: float = Field(..., description="Total revenue generated by the product")
    units_sold: int = Field(..., description="Number of units sold")

class CustomerMetrics(BaseModel):
    """Customer metrics data"""

    total_customers: int = Field(..., description="Total number of customers")
    new_customers: int = Field(..., description="Number of new customers in the period")
    inactive_customers: int = Field(..., description="Number of inactive customers in the period")
    new_customer_window_days: int = Field(..., description="Number of days to consider a customer as new")
    inactive_customer_window_days: int = Field(..., description="Number of days to consider a customer as inactive")


# chat schema

class ChatRequest(BaseModel):
    """User input question for the chat model"""

    question: str = Field(..., min_length=3, max_length=500, description="User question")

class ChatResponse(BaseModel):
    """Response from the chat model"""

    question: str
    answer: str = Field(..., description="Answer generated by the chat model")
    chart_path: Optional[str] = Field(None, description="Path to the generated chart image")


